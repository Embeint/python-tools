#!/usr/bin/env python3

"""Check that the Rust and Python CPatch implementations generate equivalent patches

Patches are generated by both implementations from synthetic firmware images. Each
implementation must apply the other's patches, and the patch sizes must be within a
small tolerance of each other (tie-breaking between equal cost encodings can differ).
"""

import argparse
import pathlib
import random
import subprocess
import sys
import tempfile

from infuse_iot.cpatch import Encoder, cpatch

ENCODERS = (Encoder.SHORTEST_PATH, Encoder.SHORTEST_PATH_DELTA, Encoder.STREAM_THUMB2)
FLASH_BASE = 0x0800_0000


def _function(rng: random.Random, n_funcs: int) -> tuple[bytearray, list[tuple[int, int]]]:
    """Function body built from a limited set of instructions, with pointers to other functions"""
    opcodes = [rng.getrandbits(16).to_bytes(2, "little") for _ in range(40)]
    body = bytearray()
    pointers = []
    for _ in range(rng.randrange(16, 256)):
        r = rng.random()
        if r < 0.08:
            # Absolute pointer to another function, filled in at layout time
            body += bytes(-len(body) % 4)
            pointers.append((len(body), rng.randrange(n_funcs)))
            body += bytes(4)
        elif r < 0.6:
            body += rng.choice(opcodes)
        else:
            body += rng.getrandbits(16).to_bytes(2, "little")
    return body, pointers


def _layout(functions: list[tuple[bytearray, list[tuple[int, int]]]]) -> bytes:
    """Place functions sequentially, resolving pointers to their final addresses"""
    addresses = []
    offset = 0
    for body, _ in functions:
        addresses.append(offset)
        offset += len(body) + (-len(body) % 4)
    image = bytearray()
    for body, pointers in functions:
        out = bytearray(body)
        for ptr_offset, target in pointers:
            out[ptr_offset : ptr_offset + 4] = (FLASH_BASE + addresses[target % len(addresses)]).to_bytes(4, "little")
        image += out + bytes(-len(out) % 4)
    # Erased flash padding to a 4 kB boundary
    return bytes(image) + b"\xff" * (-len(image) % 4096)


def firmware_pair(seed: int, n_funcs: int) -> tuple[bytes, bytes]:
    """Original and updated firmware images, where the update relocates most of the code"""
    rng = random.Random(seed)
    functions = [_function(rng, n_funcs) for _ in range(n_funcs)]
    original = _layout(functions)

    updated = [(bytearray(body), list(pointers)) for body, pointers in functions]
    # Small edits to some functions
    for body, _ in rng.sample(updated, max(1, n_funcs // 20)):
        for _ in range(rng.randrange(1, 8)):
            pos = rng.randrange(len(body))
            body[pos] = rng.getrandbits(8)
    # Remove a function and add new ones, moving everything after them
    del updated[rng.randrange(1, len(updated))]
    for _ in range(max(1, n_funcs // 30)):
        updated.insert(rng.randrange(len(updated)), _function(rng, n_funcs))
    return original, _layout(updated)


def rust(binary: str, *args: str) -> None:
    subprocess.run([binary, *args], check=True, stdout=subprocess.DEVNULL)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--rust", required=True, help="Path to the Rust `cpatch` binary")
    parser.add_argument("--tolerance", type=float, default=0.01, help="Allowed relative size difference")
    parser.add_argument("--slack", type=int, default=16, help="Allowed absolute size difference (bytes)")
    args = parser.parse_args()

    cases = [(f"seed {seed}, {n} functions", *firmware_pair(seed, n)) for seed, n in ((1, 200), (2, 600), (3, 1500))]
    failures = []
    totals = {e: [0, 0] for e in ENCODERS}

    with tempfile.TemporaryDirectory() as tmp:
        d = pathlib.Path(tmp)
        for name, original, new in cases:
            (d / "original.bin").write_bytes(original)
            (d / "new.bin").write_bytes(new)
            for encoder in ENCODERS:
                py_patch = cpatch.generate(original, new, verbose=False, encoder=encoder)
                rust(
                    args.rust,
                    "generate",
                    "--encoder",
                    encoder.value,
                    str(d / "original.bin"),
                    str(d / "new.bin"),
                    str(d / "rust.patch"),
                )
                rs_patch = (d / "rust.patch").read_bytes()

                # Each implementation applies the other's patch
                if cpatch.patch(original, rs_patch) != new:
                    failures.append(f"{name} {encoder.value}: Python failed to apply the Rust patch")
                (d / "python.patch").write_bytes(py_patch)
                rust(args.rust, "patch", str(d / "original.bin"), str(d / "python.patch"), str(d / "output.bin"))
                if (d / "output.bin").read_bytes() != new:
                    failures.append(f"{name} {encoder.value}: Rust failed to apply the Python patch")

                limit = max(args.slack, args.tolerance * len(py_patch))
                diff = len(rs_patch) - len(py_patch)
                status = "ok" if abs(diff) <= limit else "SIZE MISMATCH"
                if status != "ok":
                    failures.append(f"{name} {encoder.value}: {len(rs_patch)} vs {len(py_patch)} bytes")
                totals[encoder][0] += len(py_patch)
                totals[encoder][1] += len(rs_patch)
                print(
                    f"{name:24s} {encoder.value:20s} new {len(new):7d}  python {len(py_patch):6d}  "
                    f"rust {len(rs_patch):6d}  ({diff:+d})  {status}"
                )

        # Validation patches from both implementations are applied by both implementations
        original = cases[-1][1]
        (d / "original.bin").write_bytes(original)
        for flags in ([], ["--delta"]):
            (d / "python.patch").write_bytes(cpatch.validation(original, False, False, delta=bool(flags)))
            rust(args.rust, "validation", *flags, str(d / "original.bin"), str(d / "rust.patch"))
            for impl in ("python", "rust"):
                patch = (d / f"{impl}.patch").read_bytes()
                rust(args.rust, "patch", str(d / "original.bin"), str(d / f"{impl}.patch"), str(d / "output.bin"))
                if cpatch.patch(original, patch) != original or (d / "output.bin").read_bytes() != original:
                    failures.append(f"validation {' '.join(flags)}: {impl} patch not applied by both")
            print(f"validation {' '.join(flags) or '(base)':12s} applied by both implementations")

    for encoder, (py_total, rs_total) in totals.items():
        print(f"total {encoder.value:20s} python {py_total} rust {rs_total} ({rs_total - py_total:+d})")
    for failure in failures:
        print(f"FAIL: {failure}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
